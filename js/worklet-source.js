/* =========================================================================
   worklet-source.js – Quelltext des AudioWorklet-Prozessors
   Der Prozessor läuft im Audio-Render-Thread und kopiert die Mikrofonsamples
   unverändert (bitgenau) in Blöcke. Es findet keine Filterung, keine
   Normalisierung, keine Rauschunterdrückung und keine Dynamikbearbeitung statt.
   ========================================================================= */
(function (global) {
  'use strict';

  var SOURCE = [
    'class StimmenRecorder extends AudioWorkletProcessor {',
    '  constructor() {',
    '    super();',
    '    this.RECORDING = "recording";',
    '    this.mode = "idle";',
    '    this.bufferSize = 32768;',
    '    this.buffer = new Float32Array(this.bufferSize);',
    '    this.fill = 0;',
    '    this.frames = 0;',
    '    this.sentChunks = 0;',
    '    this.peak = 0;',
    '    this.framesSinceLevel = 0;',
    '    this.levelInterval = Math.max(128, Math.round(sampleRate / 30));',
    '    this.clips = 0;',
    '    this.port.onmessage = (event) => this.handleMessage(event.data);',
    '  }',
    '',
    '  handleMessage(message) {',
    '    if (!message || !message.type) return;',
    '    switch (message.type) {',
    '      case "start":',
    '        this.fill = 0;',
    '        this.frames = 0;',
    '        this.sentChunks = 0;',
    '        this.clips = 0;',
    '        this.peak = 0;',
    '        this.mode = this.RECORDING;',
    '        this.port.postMessage({ type: "started", sampleRate });',
    '        break;',
    '      case "pause":',
    '        this.flush();',
    '        this.mode = "paused";',
    '        this.port.postMessage({ type: "paused", frames: this.frames });',
    '        break;',
    '      case "resume":',
    '        this.mode = this.RECORDING;',
    '        this.port.postMessage({ type: "resumed", frames: this.frames });',
    '        break;',
    '      case "stop":',
    '        this.mode = "idle";',
    '        this.flush();',
    '        this.port.postMessage({ type: "stopped", frames: this.frames, chunks: this.sentChunks });',
    '        break;',
    '      default:',
    '        break;',
    '    }',
    '  }',
    '',
    '  flush() {',
    '    if (this.fill > 0) {',
    '      const out = new Int16Array(this.fill);',
    '      for (let i = 0; i < this.fill; i++) {',
    '        let s = this.buffer[i];',
    '        if (s > 1) s = 1; else if (s < -1) s = -1;',
    '        out[i] = s < 0 ? s * 32768 : s * 32767;',
    '      }',
    '      this.port.postMessage({ type: "chunk", buffer: out.buffer }, [out.buffer]);',
    '      this.sentChunks++;',
    '      this.fill = 0;',
    '    }',
    '  }',
    '',
    '  process(inputs) {',
    '    const input = inputs[0];',
    '    const channel = input && input[0];',
    '    const frames = channel ? channel.length : 128;',
    '',
    '    if (channel) {',
    '      if (this.mode === this.RECORDING) {',
    '        for (let i = 0; i < channel.length; i++) {',
    '          const sample = channel[i];',
    '          this.buffer[this.fill++] = sample;',
    '          if (this.fill === this.bufferSize) this.flush();',
    '          const abs = sample < 0 ? -sample : sample;',
    '          if (abs > this.peak) this.peak = abs;',
    '          if (abs >= 0.999) this.clips++;',
    '        }',
    '        this.frames += channel.length;',
    '      } else {',
    '        // Nicht aufnehmen: Pegel trotzdem messen, damit die Anzeige live bleibt.',
    '        for (let i = 0; i < channel.length; i++) {',
    '          const sample = channel[i];',
    '          const abs = sample < 0 ? -sample : sample;',
    '          if (abs > this.peak) this.peak = abs;',
    '          if (abs >= 0.999) this.clips++;',
    '        }',
    '      }',
    '    }',
    '',
    '    this.framesSinceLevel += frames;',
    '    if (this.framesSinceLevel >= this.levelInterval) {',
    '      this.framesSinceLevel = 0;',
    '      const db = this.peak > 0 ? 20 * Math.log10(this.peak) : -120;',
    '      this.port.postMessage({',
    '        type: "level",',
    '        peak: this.peak,',
    '        db: db,',
    '        clips: this.clips,',
    '        recording: this.mode === this.RECORDING,',
    '        frames: this.frames',
    '      });',
    '      this.peak = 0;',
    '      this.clips = 0;',
    '    }',
    '    return true;',
    '  }',
    '}',
    '',
    'registerProcessor("stimmen-recorder", StimmenRecorder);'
  ].join('\n');

  global.StimmenWorklet = { source: SOURCE };
})(window);
